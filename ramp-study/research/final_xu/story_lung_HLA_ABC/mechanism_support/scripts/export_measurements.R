suppressPackageStartupMessages({library(SingleCellExperiment);library(data.table);library(jsonlite);library(digest)})
root<-normalizePath(commandArgs(TRUE)[1]);setwd(root)
stopifnot(basename(root)=='mechanism_support',startsWith(normalizePath(tempdir()),paste0(root,'/tmp/')))
stopifnot(file.exists('results/DESIGN.json'),!file.exists('data/MEASURED_MARKERS.csv.gz'))
design<-fromJSON('results/DESIGN.json')
source<-file.path(root,'../../raw_data/lung_cancer/Cords2024/SingleCellExperiment Objects/sce_all_annotated.rds')
req<-fread('data/MEASUREMENT_REQUEST.csv.gz',colClasses=list(character=c('patient_id','roi_id')))
cat('Reading provider SCE read-only; retaining requested rows only.\n');flush.console()
sce<-readRDS(source)
markers<-c(CD73='CD73',IDO='Indoleamine 2- 3-dioxygenase (IDO)',PD1='CD279 (PD-1)',TCF1='TCF1/TCF7',FOXP3='FOXP3',
 CD3='CD3',CD4='CD4',CD8='CD8a',CD31='vWF + CD31',KI67='Ki-67',VIMENTIN='Vimentin',EPI='Pan Cytokeratin + Keratin Epithelial',CD45='CD45RA + CD45R0',HLA_DR='HLA-DR')
cat('Provider marker names:\n');print(rownames(sce));flush.console()
stopifnot('counts'%in%assayNames(sce),all(unname(markers)%in%rownames(sce)))
rows<-req$source_row_id
cd<-as.data.frame(colData(sce)[rows,c('Patient_ID','RoiID','Center_X','Center_Y','cell_category','cell_type','cell_subtype'),drop=FALSE])
stopifnot(all(as.character(cd$Patient_ID)==req$patient_id),all(as.character(cd$RoiID)==req$roi_id),all(as.character(cd$cell_type)==req$cell_type),all(as.character(cd$cell_subtype)==req$cell_subtype),all(as.character(cd$cell_category)==req$cell_category))
coord_error<-max(abs(cd$Center_X-req$x),abs(cd$Center_Y-req$y))
stopifnot(coord_error<1e-8)
x<-t(assay(sce,'counts')[unname(markers),rows,drop=FALSE]);storage.mode(x)<-'double';colnames(x)<-names(markers)
stopifnot(all(is.finite(x)),all(x>=0))
fwrite(cbind(req[,.(source_row_id,patient_id,roi_id,cell_type,cell_subtype)],as.data.table(x)),'data/MEASURED_MARKERS.csv.gz',compress='gzip')
fwrite(data.table(marker=names(markers),provider_marker=unname(markers),used_in_HLA_prediction=names(markers)%in%c('CD3','CD4','CD8','CD31','KI67','VIMENTIN','EPI','CD45','HLA_DR')),'data/MARKER_MAPPING.csv')
fwrite(data.table(provider_marker=rownames(sce)),'data/PROVIDER_ALL_MARKERS.csv')
observed_sha<-digest(file=source,algo='sha256',serialize=FALSE)
stopifnot(observed_sha==design$input_sha256$provider_sce)
write_json(list(status='PASS',source_sha256=observed_sha,n_rows=length(rows),coordinate_max_error=coord_error,all_labels_and_ids_exact=TRUE,assay='counts',source_row_indexing='1-based',measurement_sha256=digest(file='data/MEASURED_MARKERS.csv.gz',algo='sha256',serialize=FALSE)), 'results/EXPORT_VERIFICATION.json',pretty=TRUE,auto_unbox=TRUE)
writeLines(capture.output(sessionInfo()),'results/R_EXPORT_SESSION.txt')
cat('Export complete:',length(rows),'cells.\n')

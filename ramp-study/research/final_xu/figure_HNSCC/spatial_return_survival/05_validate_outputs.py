class Audit:
    def __init__(self) -> None:
        self.checks: list[dict[str, Any]] = []

    def check(
        self,
        name: str,
        condition: bool,
        *,
        observed: Any = None,
        expected: Any = None,
        detail: str | None = None,
    ) -> None:
        item: dict[str, Any] = {
            "name": name,
            "status": "PASS" if bool(condition) else "FAIL",
        }
        if observed is not None:
            item["observed"] = json_ready(observed)
        if expected is not None:
            item["expected"] = json_ready(expected)
        if detail:
            item["detail"] = detail
        self.checks.append(item)

    @property
    def failures(self) -> list[dict[str, Any]]:
        return [item for item in self.checks if item["status"] == "FAIL"]


def json_ready(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, dict):
        return {str(key): json_ready(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_ready(item) for item in value]
    return value


def load_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        value = json.load(handle)
    if not isinstance(value, dict):
        raise TypeError(f"Expected a JSON object: {path}")
    return value


def close(left: float, right: float, *, atol: float = 1e-12, rtol: float = 1e-9) -> bool:
    return bool(math.isclose(float(left), float(right), abs_tol=atol, rel_tol=rtol))


def resolve_manifest_path(value: str) -> Path:
    path = Path(value)
    return path.resolve() if path.is_absolute() else (HERE / path).resolve()


def path_is_formal(path: Path) -> bool:
    try:
        path.relative_to(FIGURE_HNSCC)
    except ValueError:
        return False
    return not any(part.lower() in BANNED_PATH_COMPONENTS for part in path.parts)


def verify_manifest_inputs(
    audit: Audit,
    return_manifest: dict[str, Any],
    feature_manifest: dict[str, Any],
    spatial_manifest: dict[str, Any],
) -> list[str]:
    raw: list[tuple[str, str]] = []
    for label, value in return_manifest["inputs"].items():
        raw.append((f"return.inputs.{label}", str(value)))
    raw.append(("features.input.path", str(feature_manifest["input"]["path"])))
    for label in ("returned_cells", "patient_quintiles", "complete_codex_cells"):
        raw.append((f"spatial.inputs.{label}", str(spatial_manifest["inputs"][label])))
    for marker, record in spatial_manifest["inputs"]["real_codex_planes"].items():
        raw.append((f"spatial.inputs.real_codex_planes.{marker}.path", str(record["path"])))

    resolved = [(label, resolve_manifest_path(value)) for label, value in raw]
    formal = all(path_is_formal(path) for _, path in resolved)
    exists = all(path.is_file() for _, path in resolved)
    audit.check(
        "all manifest inputs stay inside the formal figure_HNSCC tree",
        formal,
        observed={label: str(path) for label, path in resolved},
        expected=f"paths below {FIGURE_HNSCC} with no test/test0827 component",
    )
    audit.check(
        "all declared formal manifest inputs exist",
        exists,
        observed=[str(path) for _, path in resolved if not path.is_file()],
        expected="no missing files",
    )
    return [str(path) for _, path in resolved]


def verify_return(audit: Audit, manifest: dict[str, Any]) -> pd.DataFrame:
    program = manifest["fixed_biomarker_program"]
    audit.check(
        "fixed returned biomarker program",
        program.get("friendly_markers") == ["TIGIT", "CD39"]
        and program.get("raw_markers") == ["TIGIT--VSTM3", "CD39"],
        observed={
            "friendly_markers": program.get("friendly_markers"),
            "raw_markers": program.get("raw_markers"),
        },
        expected={
            "friendly_markers": ["TIGIT", "CD39"],
            "raw_markers": ["TIGIT--VSTM3", "CD39"],
        },
    )
    outcome = manifest.get("outcome_blinding", {})
    audit.check(
        "return stage is outcome-blind and declares no test dependency",
        outcome.get("clinical_or_survival_outcome_columns_read") is False
        and outcome.get("survival_used_for_return") is False
        and outcome.get("test_or_test0827_dependency") is False,
        observed=outcome,
        expected="all three flags false",
    )

    cells = pd.read_csv(
        RETURN_CELLS,
        dtype={"cell_uid": str, "patient": str, "unique_region": str},
        low_memory=False,
    )
    required = {
        "cell_uid",
        "patient",
        "spatial_y",
        "in_niche",
        "predicted_score",
        "within_patient_rank",
    }
    audit.check(
        "return table required columns",
        required.issubset(cells.columns),
        observed=sorted(cells.columns),
        expected=sorted(required),
    )
    audit.check(
        "return cell and patient counts",
        len(cells) == EXPECTED_CELLS and cells["patient"].nunique() == EXPECTED_PATIENTS,
        observed={"cells": len(cells), "patients": cells["patient"].nunique()},
        expected={"cells": EXPECTED_CELLS, "patients": EXPECTED_PATIENTS},
    )
    manifest_counts = manifest.get("counts", {})
    audit.check(
        "return manifest cell and patient counts",
        manifest_counts.get("haist_pt_cd8_query_cells") == EXPECTED_CELLS
        and manifest_counts.get("haist_query_patients") == EXPECTED_PATIENTS,
        observed=manifest_counts,
        expected={
            "haist_pt_cd8_query_cells": EXPECTED_CELLS,
            "haist_query_patients": EXPECTED_PATIENTS,
        },
    )
    audit.check(
        "return cell identifiers are complete and unique",
        not cells["cell_uid"].isna().any() and not cells["cell_uid"].duplicated().any(),
        observed={
            "missing": int(cells["cell_uid"].isna().sum()),
            "duplicated": int(cells["cell_uid"].duplicated().sum()),
        },
        expected={"missing": 0, "duplicated": 0},
    )

    grouped = cells.groupby("patient", sort=False)["predicted_score"]
    recomputed_rank = (grouped.rank(method="average") - 0.5) / grouped.transform("size")
    max_rank_error = float(
        np.max(
            np.abs(
                recomputed_rank.to_numpy(float)
                - cells["within_patient_rank"].to_numpy(float)
            )
        )
    )
    audit.check(
        "within-patient average-tie percentile midrank",
        max_rank_error <= 1e-12,
        observed=max_rank_error,
        expected="maximum absolute error <= 1e-12",
    )
    supplied_niche = cells["in_niche"].astype(str).str.lower().map(
        {"true": True, "false": False, "1": True, "0": False}
    )
    niche_matches = (
        not supplied_niche.isna().any()
        and np.array_equal(
            supplied_niche.to_numpy(bool), cells["spatial_y"].to_numpy(float) > 0
        )
    )
    audit.check(
        "niche flag equals spatial_y > 0",
        niche_matches,
        observed="identical" if niche_matches else "mismatch",
        expected="identical",
    )
    cells["in_niche"] = cells["spatial_y"].to_numpy(float) > 0
    cells["high_state_top40"] = cells["within_patient_rank"].ge(TOP40_THRESHOLD)
    top40_count = int(cells["high_state_top40"].sum())
    audit.check(
        "top-40% returned-state cell count",
        top40_count == EXPECTED_TOP40,
        observed=top40_count,
        expected=EXPECTED_TOP40,
    )
    return cells


def recompute_patient_features(cells: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for patient, frame in cells.groupby("patient", sort=False):
        high = frame["high_state_top40"].to_numpy(bool)
        niche = frame["in_niche"].to_numpy(bool)
        spatial = frame["spatial_y"].to_numpy(float)
        overlap = high & niche
        rows.append(
            {
                "patient": str(patient),
                "pt_cd8_cells": int(len(frame)),
                "high_state_cells": int(high.sum()),
                "non_high_state_cells": int((~high).sum()),
                "niche_cells": int(niche.sum()),
                "outside_niche_cells": int((~niche).sum()),
                "high_state_niche_cells": int(overlap.sum()),
                "high_state_outside_niche_cells": int((high & ~niche).sum()),
                "high_state_fraction": float(high.mean()),
                "niche_fraction": float(niche.mean()),
                "high_state_niche_precision": float(overlap.sum() / high.sum()),
                "high_state_niche_recall": float(overlap.sum() / niche.sum()),
                "high_pair_mean_spatial_y": float(spatial[high].mean()),
                "patient_spatial_niche_score": float(spatial.mean()),
            }
        )
    return pd.DataFrame(rows)


def verify_patient_features(audit: Audit, cells: pd.DataFrame) -> None:
    saved = pd.read_csv(PATIENT_FEATURES, dtype={"patient": str})
    recomputed = recompute_patient_features(cells)
    saved = saved.set_index("patient").sort_index()
    recomputed = recomputed.set_index("patient").sort_index()
    same_patients = saved.index.equals(recomputed.index)
    audit.check(
        "patient-feature patient set",
        same_patients and len(saved) == EXPECTED_PATIENTS,
        observed={"rows": len(saved), "same_patient_set": same_patients},
        expected={"rows": EXPECTED_PATIENTS, "same_patient_set": True},
    )
    integer_columns = [
        "pt_cd8_cells",
        "high_state_cells",
        "non_high_state_cells",
        "niche_cells",
        "outside_niche_cells",
        "high_state_niche_cells",
        "high_state_outside_niche_cells",
    ]
    float_columns = [
        "high_state_fraction",
        "niche_fraction",
        "high_state_niche_precision",
        "high_state_niche_recall",
        "high_pair_mean_spatial_y",
        "patient_spatial_niche_score",
    ]
    integer_equal = same_patients and all(
        np.array_equal(saved[column].to_numpy(int), recomputed[column].to_numpy(int))
        for column in integer_columns
    )
    audit.check(
        "patient-level integer features independently recomputed",
        integer_equal,
        observed="all equal" if integer_equal else "one or more mismatches",
        expected="all equal",
    )
    max_errors = {
        column: float(
            np.max(
                np.abs(
                    saved[column].to_numpy(float)
                    - recomputed[column].to_numpy(float)
                )
            )
        )
        for column in float_columns
    }
    audit.check(
        "patient-level continuous features independently recomputed",
        same_patients and max(max_errors.values()) <= 1e-12,
        observed=max_errors,
        expected="maximum absolute error <= 1e-12 for every feature",
    )


def verify_quintiles(audit: Audit, cells: pd.DataFrame) -> None:
    quintile_index = np.floor(cells["within_patient_rank"].to_numpy(float) * 5).astype(int) + 1
    work = cells.assign(
        state_quintile=[f"Q{value}" for value in quintile_index]
    )
    recomputed_patient = (
        work.groupby(["patient", "state_quintile"], sort=False)
        .agg(
            cells=("cell_uid", "size"),
            niche_cells=("in_niche", "sum"),
            niche_fraction=("in_niche", "mean"),
            mean_spatial_y=("spatial_y", "mean"),
        )
        .reset_index()
    )
    saved_patient = pd.read_csv(QUINTILE_PATIENT, dtype={"patient": str})
    merged = saved_patient.merge(
        recomputed_patient,
        on=["patient", "state_quintile"],
        how="outer",
        suffixes=("_saved", "_recomputed"),
        indicator=True,
    )
    same_rows = len(merged) == 368 and merged["_merge"].eq("both").all()
    patient_errors = {}
    for column in ("cells", "niche_cells", "niche_fraction", "mean_spatial_y"):
        patient_errors[column] = float(
            np.nanmax(
                np.abs(
                    merged[f"{column}_saved"].to_numpy(float)
                    - merged[f"{column}_recomputed"].to_numpy(float)
                )
            )
        )
    audit.check(
        "patient-by-quintile summary independently recomputed",
        same_rows
        and patient_errors["cells"] == 0
        and patient_errors["niche_cells"] == 0
        and patient_errors["niche_fraction"] <= 1e-12
        and patient_errors["mean_spatial_y"] <= 1e-12,
        observed={"rows": len(merged), "maximum_absolute_errors": patient_errors},
        expected={"rows": 368, "maximum_absolute_error": "<= 1e-12"},
    )

    recomputed_pooled = (
        work.groupby("state_quintile", sort=False)
        .agg(
            cells=("cell_uid", "size"),
            patients=("patient", "nunique"),
            niche_cells=("in_niche", "sum"),
            niche_fraction=("in_niche", "mean"),
            mean_spatial_y=("spatial_y", "mean"),
        )
        .reindex(["Q1", "Q2", "Q3", "Q4", "Q5"])
    )
    saved_pooled = pd.read_csv(QUINTILE_POOLED).set_index("state_quintile")
    pooled_errors = {
        column: float(
            np.max(
                np.abs(
                    saved_pooled[column].to_numpy(float)
                    - recomputed_pooled[column].to_numpy(float)
                )
            )
        )
        for column in ("cells", "patients", "niche_cells", "niche_fraction", "mean_spatial_y")
    }
    audit.check(
        "pooled quintile summary independently recomputed",
        pooled_errors["cells"] == 0
        and pooled_errors["patients"] == 0
        and pooled_errors["niche_cells"] == 0
        and pooled_errors["niche_fraction"] <= 1e-12
        and pooled_errors["mean_spatial_y"] <= 1e-12,
        observed=pooled_errors,
        expected="zero count error and continuous maximum absolute error <= 1e-12",
    )

    q1_fraction = float(recomputed_pooled.loc["Q1", "niche_fraction"])
    q5_fraction = float(recomputed_pooled.loc["Q5", "niche_fraction"])
    audit.check(
        "pooled Q1 and Q5 niche fractions",
        close(q1_fraction, 0.41174934725848567)
        and close(q5_fraction, 0.4864229765013055),
        observed={"Q1": q1_fraction, "Q5": q5_fraction},
        expected={"Q1": 0.41174934725848567, "Q5": 0.4864229765013055},
    )

    pivot = recomputed_patient.pivot(
        index="patient", columns="state_quintile", values="mean_spatial_y"
    ).dropna(subset=["Q1", "Q5"])
    delta = pivot["Q5"] - pivot["Q1"]
    positive = int(delta.gt(0).sum())
    p_value = float(
        wilcoxon(delta.to_numpy(float), alternative="greater", zero_method="wilcox").pvalue
    )
    audit.check(
        "patient-paired Q5 versus Q1 state-gradient statistic",
        len(delta) == 74
        and positive == 57
        and close(p_value, 2.044608370762729e-05, atol=1e-12, rtol=1e-8),
        observed={"patients": len(delta), "positive": positive, "wilcoxon_p": p_value},
        expected={
            "patients": 74,
            "positive": 57,
            "wilcoxon_p": 2.044608370762729e-05,
        },
    )


def verify_survival(audit: Audit) -> None:
    analysis = pd.read_csv(SURVIVAL_INPUT, dtype={"patient": str})
    patients = int(analysis["patient"].nunique())
    deaths = int(pd.to_numeric(analysis["os_event"], errors="raise").sum())
    audit.check(
        "survival analysis cohort",
        len(analysis) == 74 and patients == 74 and deaths == 24,
        observed={"rows": len(analysis), "patients": patients, "deaths": deaths},
        expected={"rows": 74, "patients": 74, "deaths": 24},
    )

    models = pd.read_csv(SURVIVAL_MODELS)
    required_models = [
        "Primary: top-40% CD8 spatial exposure",
        "Timing sensitivity: 0-60 months",
        "Fixed clinical adjustment",
        "Joint score + direct spatial score",
        "Direct spatial niche score",
        "Sensitivity: exclude Case 41403",
    ]
    audit.check(
        "all prespecified survival models are present exactly once",
        len(models) == len(required_models)
        and models["model"].is_unique
        and set(models["model"]) == set(required_models),
        observed=models["model"].tolist(),
        expected=required_models,
    )
    primary_rows = models.loc[
        models["model"].eq("Primary: top-40% CD8 spatial exposure")
    ]
    if len(primary_rows) == 1:
        primary = primary_rows.iloc[0]
        primary_observed = {
            "patients": int(primary["patients"]),
            "deaths": int(primary["deaths"]),
            "hazard_ratio_per_sd": float(primary["hazard_ratio_per_sd"]),
            "wald_p": float(primary["wald_p"]),
        }
        primary_ok = (
            primary_observed["patients"] == 74
            and primary_observed["deaths"] == 24
            and close(primary_observed["hazard_ratio_per_sd"], 1.89146297892615, rtol=1e-8)
            and close(primary_observed["wald_p"], 0.0014499619384292, rtol=1e-8)
        )
    else:
        primary_observed = {"rows": len(primary_rows)}
        primary_ok = False
    audit.check(
        "primary Cox result",
        primary_ok,
        observed=primary_observed,
        expected={
            "patients": 74,
            "deaths": 24,
            "hazard_ratio_per_sd": 1.89146297892615,
            "wald_p": 0.0014499619384292,
        },
    )
    numeric = [
        "patients",
        "deaths",
        "beta",
        "se",
        "hazard_ratio_per_sd",
        "ci95_low",
        "ci95_high",
        "wald_p",
        "feature_ph_p",
        "global_ph_p",
        "concordance",
    ]
    finite = np.isfinite(models[numeric].to_numpy(float)).all()
    sensible = (
        models["hazard_ratio_per_sd"].gt(0).all()
        and models["ci95_low"].gt(0).all()
        and models["ci95_high"].gt(models["ci95_low"]).all()
    )
    audit.check(
        "survival model estimates are finite and internally ordered",
        finite and sensible,
        observed={"all_finite": bool(finite), "positive_ordered_intervals": bool(sensible)},
        expected={"all_finite": True, "positive_ordered_intervals": True},
    )


def valid_signature(path: Path) -> bool:
    with path.open("rb") as handle:
        prefix = handle.read(8)
    if path.suffix.lower() == ".png":
        return prefix == b"\x89PNG\r\n\x1a\n"
    if path.suffix.lower() == ".pdf":
        return prefix.startswith(b"%PDF")
    return False


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


